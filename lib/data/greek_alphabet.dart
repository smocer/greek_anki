// IPA reference: https://en.wikipedia.org/wiki/Greek_alphabet
// Paths are original teaching diagrams in a 100 × 100 coordinate space.
// They illustrate one handwriting convention, not a mandatory stroke order.
class GreekLetter {
  const GreekLetter(
    this.upper,
    this.lower,
    this.name,
    this.reading,
    this.nameIpa,
    this.sound,
    this.upperStrokes,
    this.lowerStrokes,
  );

  final String upper, lower, name, reading, nameIpa, sound;
  final List<String> upperStrokes, lowerStrokes;

  String get audioAsset =>
      'audio/greek/native-name-${lower.runes.first.toRadixString(16)}.mp3';
}

