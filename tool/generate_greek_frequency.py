#!/usr/bin/env python3
"""Extract reproducible offline frequency counts for the app's Greek spellings.

Download https://object.pouta.csc.fi/OPUS-OpenSubtitles/v2024/freq/el.freq.gz
then run: python3 tool/generate_greek_frequency.py /path/to/el.freq.gz
No translation/explanation text is submitted to a service.
"""
import argparse
import gzip
import hashlib
import json
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'lib/domain/greek_frequency_data.dart'
GREEK = re.compile(r'[\u0370-\u03ff\u1f00-\u1fff\u0300-\u036f]+')


def key(text):
    return unicodedata.normalize('NFD', text.lower()).replace('ς', 'σ')


def vocabulary_tokens():
    tokens = set()
    for path in [ROOT / 'assets/dictionary/greek.json',
                 *sorted((ROOT / 'assets/dictionary/additions').glob('*.json'))]:
        data = json.loads(path.read_text())
        cards = data['cards'].values() if 'cards' in data else data['words']
        for card in cards:
            texts = [card['greek'], *card.get('alternatives', []),
                     *card.get('acceptedAnswers', [])]
            texts.extend(form['greek'] for form in card.get('forms', []))
            for text in texts:
                tokens.update(key(word) for word in GREEK.findall(text))
    return tokens


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('corpus', type=Path)
    args = parser.parse_args()
    counts = dict.fromkeys(vocabulary_tokens(), 0)
    with gzip.open(args.corpus, 'rt', encoding='utf-8') as source:
        for line in source:
            parts = line.strip().split(maxsplit=1)
            # OPUS includes whitespace-only tokens, which have no Greek spelling.
            if len(parts) == 1 and parts[0].isdigit():
                continue
            count, word = parts
            normalized = key(word)
            if normalized in counts:
                counts[normalized] += int(count)
    checksum = hashlib.sha256(args.corpus.read_bytes()).hexdigest()
    lines = [
        '// Generated by tool/generate_greek_frequency.py; do not edit.',
        '// OPUS OpenSubtitles v2024, Greek word-form counts.',
        '// Source attribution and limitations: docs/word-frequency.md',
        f'// Source gzip SHA-256: {checksum}',
        'const greekFrequencyCounts = <String, int>{',
        *[f'  {json.dumps(word, ensure_ascii=False)}: {count},'
          for word, count in sorted(counts.items())],
        '};', '',
    ]
    OUTPUT.write_text('\n'.join(lines))
    print(f'Generated {len(counts)} tokens; {sum(v == 0 for v in counts.values())} unattested (rank last).')
    print('Source SHA-256:', checksum)


if __name__ == '__main__':
    main()
